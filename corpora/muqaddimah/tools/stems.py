"""STEMS: words CAMeL's database lacks, completed by hand (see patches.py).

Keyed by the stem as written without proclitics, article and enclitic pronoun (diacritics are not part of a key; أ إ آ
and ة ه may be written either way unless two keys differ only in them, when the exact spelling wins). The value is
(lemma, UPOS, root, FEATS); a lemma of None is the key itself (a name's lemma is its written stem). A word the database
lacks that has no entry here keeps CAMeL's guess, and a name needs no entry unless CAMeL guessed it a common noun.
Roots are CAMeL-style (dot-joined radicals, # for a weak radical left open); words from other languages have none.
"""

_G = {"m": "Masc", "f": "Fem"}
_N = {"s": "Sing", "d": "Dual", "p": "Plur"}


def _nominal(g, n):
    return "|".join(f for f in (f"Gender={_G[g]}" if g else "", f"Number={_N[n]}" if n else "") if f)


def N(lemma, root=None, g=None, n=None):
    return (lemma, "NOUN", root, _nominal(g, n))


def A(lemma, root=None, g=None, n=None):
    return (lemma, "ADJ", root, _nominal(g, n))


def P(lemma=None):
    return (lemma, "PROPN", None, "")


def X():
    """A letter-word of the zāʾiraja or a foreign word: not Arabic, kept as written."""
    return (None, "X", None, "")


def V(lemma, root, aspect, voice, person, g, n, mood=None):
    feats = ["VerbForm=Fin", f"Aspect={'Perf' if aspect == 'p' else 'Imp'}", f"Voice={'Act' if voice == 'a' else 'Pass'}",
             f"Person={person}", f"Gender={_G[g]}", f"Number={_N[n]}"]
    if mood:
        feats.append(f"Mood={mood}")
    elif aspect == "i":
        feats.append("Mood=Ind")
    return (lemma, "VERB", root, "|".join(feats))


